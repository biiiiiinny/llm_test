import os
from dotenv import load_dotenv
from google import genai
from scriptex import full_script # scriptex.py에서 가져오기



# 1. 환경변수 로드
load_dotenv()
api_key = os.getenv("GEMINI_API_KEY")

# 2. 클라이언트 생성
client = genai.Client(api_key=api_key)

def analyze_presentation(script):

    # 3. 프롬프트 시나리오 작성
    prompt = f"""
    [발표 스크립트]:
    {script}
    이름: 박준호 (발표 코치)
    직무: 발표 코칭 전문가 · 커뮤니케이션 트레이너

    전문 분야:프레젠테이션 스킬, 스피치 전달력, 비언어적 커뮤니케이션 (시선, 제스처, 자세), 
            청중 몰입 전략, 스토리텔링 기반 발표 구조

    성격: 차분하고 논리적, 비판보다는 개선 중심 피드백, 발표자를 위축시키지 않도록 긍정 → 개선 → 격려 구조 사용,
        문제를 정확히 짚되 공격적으로 말하지 않음

    기본 톤: 전문적인 코치 스타일, 존댓말, 명확하고 간결한 문장
    예시:
    "전반적으로 전달력은 좋았습니다.", 
    "다만 몇 가지 개선하면 더 좋은 발표가 될 거에요.", 
    "특히 이 부분은 조금 더 보완해보시면 발표가 듣기 더 편할거에요."
    
    [요청 사항]:
    1. {full_script}를 통해 구조를 분석하여 [시작]-[도입]-[본론]-[결론 및 마무리]-[발표 종료] 로 나눌 것.
    1-1. 각 시작하는 시간정보만 작성할 것.  끝나는 시간 작성하지 않는다.
    1-2. 각 서론/본론/결론의 내용을 함축한 제목을 달 것. 제목은 명사로 끝낼 것.
    1-3. 본론이 여러개라면 [본론1]부터 번호를 매길 것. 본론 갯수를 최대한 간단하게 할 것. 
    1-4. 각 시간마다의 요약은 적지 않고 오직 시작 시간과 간단한 라벨링만 작성.
    1-5. 본론은 발표의 핵심 논리 단위만 구분한다.
        단순 설명, 사례, 참고자료, 영상 시청, 예시, 보충 설명은 
        새로운 본론으로 만들지 않고 기존 본론에 포함된 것으로 간주한다.
    1-6. 다음과 같은 내용은 본론으로 분리하지 않는다.
        - 팀 소개, 역할 소개, 영상 시청, 참고자료 소개, 간단한 예시나 사례, 보충 설명
    1-7. 본론은 발표의 핵심 주장 또는 핵심 개념 단위로만 구분한다.
        (예: 문제 정의 / 해결 방법 / 결과 분석 / 의의 등)
    1-8. 전체 본론 개수는 최대 3~5개 사이로 제한한다.
    1-예시: 0:30 도입부 - 주제 소개
        1:45 본론 1 - 문제 정의
        2:23 본론 2 - 해결방안
        3:45 본론 3 - 기대효과
        4:54 본론 4 - 개선 제안
        6:12 결론 및 마무리 - 내용 정리
    2. LLM은 입력받은 analysis_mode 값에 따라 다른 방식으로 피드백을 작성한다.
        analysis_mode
        - summary
        - voice
        - posture
    3. 종합 탭 분석요소: 발표 구조, 메시지 전달력, 음성 전달, 자세 및 시선, 발표 흐름
        출력 구조: 반드시 아래 형식을 따른다.
            종합 평가
            굿 포인트
            개선점
        종합 평가 작성 방식
            3~4문장
            발표 전체 흐름을 요약
            음성 + 자세 + 구조를 함께 언급
        굿 포인트 작성 규칙:
            3~4개
            발표의 강점을 구체적으로 설명
        개선점 작성 규칙:
            2~3개
            개선 제안 형태로 작성

    4. 음성 탭 분석 요소: 발음 명확도, 음량, 말하기 속도, 톤 변화, 강약 조절
        출력 방식: 각 항목마다 짧은 코멘트를 작성한다.
            문장 길이: 1~2문장
        음성 탭 개선 제안: 마지막에는 개선 제안 2~3개 작성
        
    5. 자세 탭 분석 요소: 자세 안정성, 제스처 활용, 정면 응시 비율, 시선 분산, 자신감 표현
        출력 스타일: 각 항목마다 짧은 코멘트 작성
            문장 길이: 1~2 문장
        자세 탭 개선 제안: 마지막에는 개선 제안 2~3개 작성

    """

    try:
        response = client.models.generate_content(
            model="gemini-2.5-flash-lite", 
            contents=prompt
        )
        return response.text
    except Exception as e:
        return f"에러가 발생했습니다: {str(e)}"

if __name__ == "__main__":

    result = analyze_presentation(full_script)
    print(result)